#!/usr/bin/env node

/**
 * tools/script-reference.mjs: generate docs/script-reference.md from
 * package.json.
 *
 * WHY The root package.json carries 56 scripts, and until now the only complete
 * list of them was the file itself: the docs describe the ones a contributor
 * needs and link out for the rest, so "what runs `check:gates`", "which script
 * owns the coverage report" or "what did `docs:downloads` become" meant reading
 * (or grepping) JSON. A hand-written table would answer that once and then rot:
 * the renames in the script surface are exactly the kind of change that leaves
 * a table naming a script that no longer exists, with nothing failing.
 *
 * This page is therefore DERIVED. Every script name and every command body
 * comes from package.json, grouped by tools/scriptSections.mjs (the same
 * ordered section list the unit test pins the block against), and `pnpm
 * check:script-reference` fails when the committed page no longer matches. The
 * one hand-written part is the header prose above the first section.
 *
 * A script that matches no section is a hard error rather than a missing row,
 * so the page cannot silently lose a script the block gains.
 *
 * USAGE
 *
 * node tools/script-reference.mjs --write regenerate docs/script-reference.md
 * node tools/script-reference.mjs --check fail when the page is stale (CI)
 */

import {readFileSync, writeFileSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';

import prettier from 'prettier';

import prettierConfig from '../config/prettier.config.js';
import {SCRIPT_SECTIONS, sectionOf} from './scriptSections.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PACKAGE_JSON = path.join(ROOT, 'package.json');
const PAGE = path.join(ROOT, 'docs', 'script-reference.md');

/**
 * The heading text of each section. A docs page over 100 lines carries a
 * contents list (CONTRIBUTING.md, TOC-on-touch), and this page grows past that
 * on its own, so the list is generated alongside the sections rather than
 * hand-kept.
 */
const SECTION_TITLES = {
  lint: 'Lint and format',
  format: 'Formatting',
  test: 'Tests',
  check: 'Repository contracts',
  hooks: 'Git hooks',
  docs: 'Docs site',
  toolchain: 'Toolchain',
  scan: 'Binary scanning',
  snapshot: 'Offline snapshots',
  publish: 'Publishing',
  release: 'Release housekeeping',
  review: 'AI review',
  ci: 'CI helpers',
};

/**
 * Group a `scripts` object into the documented sections, preserving the order
 * each section's entries appear in.
 *
 * @param {Record<string, string>} scripts the package.json `scripts` block
 * @returns {Map<string, [string, string][]>} section name to [name, body] pairs
 */
export function groupScripts(scripts) {
  const groups = new Map(SCRIPT_SECTIONS.map(([name]) => [name, []]));
  for (const [name, body] of Object.entries(scripts)) {
    const section = sectionOf(name);
    if (!section) {
      throw new Error(
        `\`${name}\` matches no section in tools/scriptSections.mjs: add it there before the page can list it`
      );
    }
    groups.get(section).push([name, body]);
  }
  return groups;
}

/**
 * Render the page: one fenced block per section, each line `pnpm <name>` with
 * the script body as a trailing comment so the page answers "what does this
 * run" without a second lookup.
 *
 * @param {Record<string, string>} scripts the package.json `scripts` block
 * @returns {string} unformatted markdown
 */
export function renderReference(scripts) {
  const groups = groupScripts(scripts);
  const lines = [
    '# Script reference',
    '',
    'Every `pnpm` script in [`package.json`](../package.json), grouped the way the block is ordered',
    'there. The command body is the script itself, so a flag shown here is the flag that runs.',
    '',
    `This page is generated by \`node tools/script-reference.mjs --write\`. \`pnpm check:script-reference\` fails it when the page no longer matches \`package.json\`, so regeneration and not editing is the way to change it.`,
    '',
  ];

  const present = [...groups].filter(([, entries]) => entries.length > 0);
  for (const [section] of present) {
    const title = SECTION_TITLES[section] ?? section;
    lines.push(`- [${title}](#${title.toLowerCase().replaceAll(/[^a-z0-9]+/g, '-')})`);
  }
  lines.push('');

  for (const [section, entries] of present) {
    if (entries.length === 0) continue;
    const width = Math.max(...entries.map(([name]) => name.length));
    lines.push(`## ${SECTION_TITLES[section] ?? section}`, '', '```text');
    for (const [name, body] of entries) {
      lines.push(`pnpm ${name.padEnd(width)}  # ${body}`);
    }
    lines.push('```', '');
  }

  const total = Object.keys(scripts).length;
  lines.push(
    `${total} scripts in ${SCRIPT_SECTIONS.length} sections. \`pnpm lint\` composes the \`lint\` stages;`,
    '`pnpm lint:all` runs them all and reports every finding at once.',
    ''
  );
  return lines.join('\n');
}

/**
 * Run generated markdown through the repo's own prettier config, so the
 * committed page is byte-identical to what `pnpm format` expects.
 *
 * @param {string} source the generated markdown
 * @returns {Promise<string>} the formatted page
 */
async function format(source) {
  return prettier.format(source, {...prettierConfig, plugins: [], filepath: PAGE});
}

async function main() {
  const args = process.argv.slice(2);
  const write = args.includes('--write');
  const check = args.includes('--check');
  if (!write && !check) {
    throw new Error('usage: node tools/script-reference.mjs --write | --check');
  }

  const {scripts} = JSON.parse(readFileSync(PACKAGE_JSON, 'utf8'));
  const page = await format(renderReference(scripts));

  if (write) {
    writeFileSync(PAGE, page, 'utf8');
    console.log(
      `script-reference: wrote docs/script-reference.md (${Object.keys(scripts).length} scripts)`
    );
    return;
  }

  const current = readFileSync(PAGE, 'utf8').replaceAll('\r\n', '\n');
  if (current !== page) {
    throw new Error(
      'docs/script-reference.md is stale: run `node tools/script-reference.mjs --write` and commit the result'
    );
  }
  console.log('script-reference: docs/script-reference.md matches package.json');
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  try {
    await main();
  } catch (err) {
    console.error(`script-reference: ${err.message}`);
    process.exit(1);
  }
}
